namespace LekhaBook.Contracts;

// Parties, money accounts and party categories (AGENT_PLAN § 5.1). Enum values travel as strings:
// PartyType "Customer"/"Supplier"; OpeningSide "ToReceive"/"ToGive"; money account Type "Cash"/"Bank"/"Cheque"/"Wallet".
// Balances are computed on every read and never sent back to the server.

/// <summary>A customer or supplier. <paramref name="Balance"/> is signed: positive = To Receive, negative = To Give.</summary>
public sealed record PartyDto(
    Guid Id,
    string Name,
    string PartyType,
    string? Phone,
    string? Email,
    string? Address,
    string? Pan,
    Guid? CategoryId,
    string? CategoryName,
    decimal OpeningBalance,
    string OpeningSide,
    DateOnly? OpeningAsOf,
    decimal Balance,
    DateTime CreatedAtUtc);

/// <summary>Create or edit a party. On create, <paramref name="Id"/> is generated by the client (UUIDv7) so a retried request can't add the party twice; null lets the server pick one. Ignored on edit.</summary>
public sealed record SavePartyRequest(
    string Name,
    string PartyType,
    string? Phone = null,
    string? Email = null,
    string? Address = null,
    string? Pan = null,
    Guid? CategoryId = null,
    decimal OpeningBalance = 0,
    string OpeningSide = "ToReceive",
    DateOnly? OpeningAsOf = null,
    Guid? Id = null);

/// <summary>Cash, bank, cheque or wallet account. <paramref name="Balance"/> is the money held (negative = overdrawn).</summary>
public sealed record MoneyAccountDto(
    Guid Id,
    string Name,
    string Type,
    string? AccountHolderName,
    string? AccountNumber,
    decimal OpeningBalance,
    DateOnly? OpeningAsOf,
    bool IsSystem,
    decimal Balance);

/// <summary>Create or edit a money account. <paramref name="OpeningBalance"/> is the "current account balance" when the
/// account is added, and may be negative (an overdrawn bank account). Same <paramref name="Id"/> rule as parties.</summary>
public sealed record SaveMoneyAccountRequest(
    string Name,
    string Type,
    string? AccountHolderName = null,
    string? AccountNumber = null,
    decimal OpeningBalance = 0,
    DateOnly? OpeningAsOf = null,
    Guid? Id = null);

public sealed record PartyCategoryDto(Guid Id, string Name);

public sealed record SavePartyCategoryRequest(string Name, Guid? Id = null);

/// <summary>An account statement: the opening balance, then each entry with the running balance after it.</summary>
public sealed record LedgerDto(Guid AccountId, decimal OpeningBalance, DateOnly? OpeningAsOf, IReadOnlyList<LedgerLineDto> Lines, decimal ClosingBalance);

/// <summary>One statement line. Debit raises the balance, credit lowers it; <paramref name="OtherAccount"/> is the party or account on the other side.</summary>
public sealed record LedgerLineDto(
    Guid TransactionId,
    string Type,
    string VoucherNo,
    DateOnly Date,
    decimal Debit,
    decimal Credit,
    decimal Balance,
    string? OtherAccount,
    string? Remarks);

// Transactions (AGENT_PLAN § 5.2, D15). One row moves value From (credited) one account To (debited) another;
// Type is a TransactionType name and decides which kinds of account fit each side.

/// <summary>An income or expense head. <paramref name="Type"/> is "Income" or "Expense".</summary>
public sealed record CategoryDto(Guid Id, string Name, string Type);

/// <summary>A saved entry. <paramref name="Status"/> is "Posted" or "Void".</summary>
public sealed record TransactionDto(
    Guid Id,
    Guid CompanyId,
    string Type,
    string VoucherNo,
    DateOnly Date,
    decimal Amount,
    Guid FromAccountId,
    Guid ToAccountId,
    string? Remarks,
    string? ChequeNo,
    DateOnly? ChequeDate,
    string Status,
    Guid CreatedBy,
    DateTime CreatedAtUtc);

/// <summary>
/// A new entry. <paramref name="Id"/> is generated by the client (UUIDv7) so a retried request can't add it
/// twice. A null <paramref name="Date"/> means today in the company's time zone.
/// </summary>
public sealed record CreateTransactionRequest(
    string Type,
    DateOnly? Date,
    decimal Amount,
    Guid FromAccountId,
    Guid ToAccountId,
    string? Remarks = null,
    string? ChequeNo = null,
    DateOnly? ChequeDate = null,
    Guid? Id = null);

/// <summary>
/// An edit sends every editable field, so a cleared field is cleared. The type can't change;
/// <paramref name="Type"/> may be sent to confirm it. Voiding is a DELETE, not an edit.
/// </summary>
public sealed record UpdateTransactionRequest(
    DateOnly Date,
    decimal Amount,
    Guid FromAccountId,
    Guid ToAccountId,
    string? Remarks = null,
    string? ChequeNo = null,
    DateOnly? ChequeDate = null,
    string? Type = null);

/// <summary>A photo or PDF proof attached to a transaction.</summary>
public sealed record AttachmentDto(
    Guid Id,
    Guid? TransactionId,
    Guid? AccountId,
    string FileName,
    string ContentType,
    long SizeBytes,
    string? StorageKey,
    DateTime CreatedAtUtc);


// Sync (AGENT_PLAN § 6, D17).

/// <summary>
/// One queued device change. <paramref name="EntityType"/> is "Transaction" or "PartyCategory";
/// <paramref name="Operation"/> is "Create", "Update" or "Void". <paramref name="Payload"/> is JSON: a
/// <see cref="CreateTransactionRequest"/> (with its id), a <see cref="SyncUpdatePayload"/>, a
/// <see cref="SyncVoidPayload"/> or a <see cref="SavePartyCategoryRequest"/> (with its id).
/// <paramref name="BaseVersion"/> is the server version an update or void was made from.
/// </summary>
public sealed record PushItem(
    string EntityType,
    string Operation,
    string Payload,
    string IdempotencyKey,
    long BaseVersion = 0);

public sealed record SyncUpdatePayload(Guid Id, UpdateTransactionRequest Entry);

public sealed record SyncVoidPayload(Guid Id);

/// <summary>Result of processing one push item.</summary>
public sealed record PushItemResult(
    string IdempotencyKey,
    bool Ok,
    string? Error,
    string? FinalVoucherNo,
    long? Version);

/// <summary>Request to push a batch of outbox items.</summary>
public sealed record PushRequest(IReadOnlyList<PushItem> Items);

/// <summary>Response from a push batch.</summary>
public sealed record PushResponse(IReadOnlyList<PushItemResult> Results);

/// <summary>One row returned by pull (includes soft-deleted rows).</summary>
public sealed record PulledRow(
    string EntityType,
    Guid Id,
    long Version,
    DateTime UpdatedAtUtc,
    Guid? UpdatedBy,
    string? UpdatedOnDevice,
    bool IsDeleted,
    string Payload);

/// <summary>
/// Rows changed since the given version, oldest first. <paramref name="LatestVersion"/> is the cursor to ask from
/// next: the last row's version when the page is full, otherwise the company's latest version.
/// </summary>
public sealed record PullResponse(
    long LatestVersion,
    IReadOnlyList<PulledRow> Rows);
